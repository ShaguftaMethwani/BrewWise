from datetime import datetime, timezone
import uuid
from typing import List, Optional, Literal, Dict, Any
from pydantic import BaseModel, Field, model_validator


class PourStep(BaseModel):
    step_number: int
    water_g: float
    cumulative_water_g: float
    start_time_seconds: int
    duration_seconds: int
    technique: str = Field(description="e.g. gentle centre pour, spiral outward pour")
    notes: Optional[str] = None


class RecipeExplanation(BaseModel):
    reasoning_summary: str = Field(description="Summary of recipe reasoning based on roast and process")
    parameter_rationale: Dict[str, str] = Field(default_factory=dict, description="Rationale per parameter (ratio, grind, temp)")
    assumptions: List[str] = Field(default_factory=list, description="Assumptions made about the coffee or water")


class TroubleshootingTip(BaseModel):
    symptom: str = Field(description="e.g. tastes sour, tastes astringent/bitter, brews too fast")
    likely_cause: str
    adjustment: str


class Adaptation(BaseModel):
    parameter: str
    original_value: str
    adapted_value: str
    rationale: str


class SourceReference(BaseModel):
    source_name: str
    url: Optional[str] = None
    similarity_score: Optional[float] = None


class RecipeGenerationOutput(BaseModel):
    """Slim schema generated by Gemini Flash LLM in a single call."""
    dose_g: float = Field(default=15.0, description="Dose in grams")
    water_g: float = Field(default=240.0, description="Total brew water in grams")
    ratio: str = Field(default="1:16", description="Coffee to water ratio")
    water_temperature_c: int = Field(default=93, description="Water temperature in Celsius (85-99)")
    grind_description: str = Field(default="Medium-fine, table salt consistency")
    grind_setting: Optional[str] = Field(default=None, description="Specific clicks or setting if grinder provided")
    filter_prep: Optional[str] = Field(default="Rinse paper filter thoroughly with hot water")
    bloom_water_g: float = Field(default=45.0, description="Bloom water in grams (2-3x dose)")
    bloom_time_seconds: int = Field(default=45, description="Bloom duration in seconds (30-60)")
    pour_schedule: List[PourStep] = Field(default_factory=list)
    target_brew_time_seconds: int = Field(default=180, description="Total target drawdown time in seconds")
    step_by_step_instructions: List[str] = Field(default_factory=list)
    expected_flavour: str = Field(default="Bright, clean cup with distinct fruit notes")
    explanation: RecipeExplanation
    troubleshooting: List[TroubleshootingTip] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)


class PersonalisedRecipe(BaseModel):
    """Full hydrated and verified recipe."""
    recipe_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    coffee_profile_id: str
    source_type: Literal["exact_match", "adapted_from_related", "ai_generated", "curated_baseline"] = "ai_generated"
    source_recipes: List[SourceReference] = Field(default_factory=list)
    generation_model: Optional[str] = "gemini-2.5-flash"

    # Equipment
    dripper: str = "Hario V60"
    grinder: Optional[str] = "General Grinder"
    filter_type: Optional[str] = "Paper"

    # Brew Parameters
    dose_g: float
    water_g: float
    ratio: str
    water_temperature_c: int
    grind_description: str
    grind_setting: Optional[str] = None

    # Procedure
    filter_prep: Optional[str] = None
    bloom_water_g: float
    bloom_time_seconds: int
    pour_schedule: List[PourStep]
    target_brew_time_seconds: int
    step_by_step_instructions: List[str]

    # Reasoning & Quality
    expected_flavour: str
    flavour_is_prediction: bool = True
    explanation: RecipeExplanation
    troubleshooting: List[TroubleshootingTip]
    adaptations: List[Adaptation] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    confidence: float = 0.85
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @model_validator(mode="after")
    def validate_arithmetic(self) -> "PersonalisedRecipe":
        # Validate that total pour water matches total water within 1g tolerance
        total_pours = sum(p.water_g for p in self.pour_schedule)
        if self.pour_schedule and abs(total_pours - self.water_g) > 1.0:
            raise ValueError(f"Sum of pour schedule ({total_pours}g) must equal water_g ({self.water_g}g)")
        return self


class RecipeGenerateRequest(BaseModel):
    coffee_profile_id: str
    dripper: Optional[str] = "Hario V60"
    grinder: Optional[str] = None
    dose_preference_g: Optional[float] = None
    target_strength: Optional[Literal["light", "balanced", "strong"]] = "balanced"
